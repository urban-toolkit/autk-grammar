const DEFAULT_SEQUENTIAL: RGB[] = SEQUENTIAL_SCALES.interpolateViridis;
const DEFAULT_CATEGORICAL: RGB[] = CATEGORICAL_SCALES.schemeTableau10;

function lerpChannel(a: number, b: number, t: number): number {
    return Math.round(a + (b - a) * t);
}

function interpolateStops(stops: RGB[], t: number): RGB {
    const clamped = Math.max(0, Math.min(1, t));
    const n = stops.length - 1;
    const i = Math.min(Math.floor(clamped * n), n - 1);
    const localT = clamped * n - i;
    const a = stops[i];
    const b = stops[i + 1];
    return [lerpChannel(a[0], b[0], localT), lerpChannel(a[1], b[1], localT), lerpChannel(a[2], b[2], localT)];
}

export function sequentialColor(interpolator: ColorMapInterpolator, t: number): RGB {
    const stops = SEQUENTIAL_SCALES[interpolator] ?? DEFAULT_SEQUENTIAL;
    return interpolateStops(stops, t);
}

export function categoricalColor(interpolator: ColorMapInterpolator, index: number): RGB {
    const palette = CATEGORICAL_SCALES[interpolator] ?? DEFAULT_CATEGORICAL;
    return palette[index % palette.length];
}

export function isCategoricalScale(interpolator: ColorMapInterpolator): boolean {
    return interpolator in CATEGORICAL_SCALES;
}
